export const GO_LYNX_BUNDLE_BASE_URL = 'https://go.lynxjs.org/lynx-examples/'

export interface GoLynxBundleExample {
  /** URL 中的一级示例目录，例如 css-api。 */
  category: string
  /** 用于列表展示的 Bundle 文件名，不包含 .lynx.bundle。 */
  name: string
  /** 相对 lynx-examples 根目录的稳定路径。 */
  path: string
  /** 可直接交给原生 Lynx 容器加载的 HTTPS Bundle URL。 */
  url: string
}

export const GO_LYNX_BUNDLE_EXAMPLES: GoLynxBundleExample[] =
  GO_LYNX_BUNDLE_PATHS.map((path) => {
    const segments = path.split('/')
    const fileName = segments[segments.length - 1] || path
    return {
      category: segments[0] || 'other',
      name: fileName.replace(/\.lynx\.bundle$/i, ''),
      path,
      url: `${GO_LYNX_BUNDLE_BASE_URL}${path}`,
    }
  })

export const GO_LYNX_BUNDLE_CATEGORIES = Array.from(
  new Set(GO_LYNX_BUNDLE_EXAMPLES.map((item) => item.category)),
).sort()
